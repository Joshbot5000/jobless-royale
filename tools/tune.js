// Automatic stat tuner. Reads duel results (tools/duel.js) and nudges each troop/building's HP and damage
// multipliers in src/data_tune.js, then you rebuild and duel again (tools/balance.sh runs the loop).
// Each card gets a power score inside its own arena, in elixir per duel:
//   troops:            (attack net + defence net) / 2      buildings: defence net
// and is pulled towards its arena's median power, so no card is far better or worse than its neighbours.
// Specialists are fine (great on defence, poor on attack, or the reverse); being great at both is not.
// Real threats (400+ tower damage when undefended) with fewer than 3 answers in their arena are nerfed extra.
// Multipliers are renormalised every round (geometric mean 1), so cards keep their strength against towers.
const fs=require('fs'), path=require('path'), {execFileSync}=require('child_process');
const IN=process.argv[2]||path.resolve(__dirname,'..','dist','duels.json');
const OUT=path.resolve(__dirname,'..','src','data_tune.js');
const rep=JSON.parse(execFileSync('node',[path.resolve(__dirname,'duelreport.js'),IN,'--json'],{maxBuffer:64<<20}).toString());
const D=JSON.parse(fs.readFileSync(IN,'utf8'));
let T={}; if(fs.existsSync(OUT)){ const m=fs.readFileSync(OUT,'utf8').match(/const TUNE=(\{[\s\S]*?\});/); if(m) T=JSON.parse(m[1]); }
const err={};
for(const id in rep){ const a=D[id];
  const rows=rep[id].filter(r=>a.att.includes(r.k)||r.defNet.length&&r.solo===null);
  const pw=r=>a.att.includes(r.k)?(r.att+r.def)/2:r.def;
  const cand=rows.filter(r=>a.type[r.k]!=='spell');
  const ps=cand.map(pw).sort((x,y)=>x-y), med=ps[ps.length>>1];
  for(const r of cand){
    let e=pw(r)-med;
    if(a.att.includes(r.k)&&(r.solo||0)>=400&&r.countersOf.length<3) e+=0.6*(3-r.countersOf.length);
    (err[r.k]=err[r.k]||[]).push(e); } }
// spells: tuned by hand (their value is mostly offensive and situational)
const spells=new Set(); for(const id in D){ for(const k of D[id].def) if(D[id].type[k]==='spell') spells.add(k); }
let changed=0;
for(const k in err){ if(spells.has(k)) continue; const e=err[k].reduce((s,x)=>s+x,0)/err[k].length; if(Math.abs(e)<0.35) continue;
  const step=Math.exp(-0.07*Math.max(-3,Math.min(3,e)));
  const [h,d]=T[k]||[1,1]; T[k]=[h*step,d*step]; changed++; }
// renormalise so the average card keeps its strength against the towers
const vals=Object.values(T); if(vals.length){ const g=Math.exp(vals.reduce((s,[h])=>s+Math.log(h),0)/vals.length);
  for(const k in T){ T[k]=T[k].map(x=>Math.round(Math.min(1.8,Math.max(0.5,x/g))*1000)/1000); } }
const body=`// GENERATED by tools/tune.js from duel results (tools/duel.js). Do not edit by hand: change
// data_balance.js or the rules in tools/tune.js and re-run tools/balance.sh.
// Each entry multiplies a card's [HP, damage] (damage includes pulse/every-Nth ability damage and death blasts).
const TUNE=${JSON.stringify(T)};
for(const k in TUNE){ const c=CARDS[k]; if(!c) continue; const [h,d]=TUNE[k];
  if(c.hp) c.hp=Math.round(c.hp*h); if(c.dmg) c.dmg=Math.round(c.dmg*d);
  if(c.sp&&c.sp.dmg&&c.type!=='spell') c.sp={...c.sp,dmg:Math.round(c.sp.dmg*d)};
  if(c.death&&c.death.blast) c.death={...c.death,blast:[c.death.blast[0],Math.round(c.death.blast[1]*d)]}; }
`;
fs.writeFileSync(OUT,body); console.log(`tuned ${changed} cards (${Object.keys(T).length} with multipliers)`);
