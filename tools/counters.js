// Builds src/data_counters.js from duel results: for every attacker in every arena, the defenders that really answer
// it (stop the push without losing the trade), best first. The AI on Normal/Hard uses it to pick its defence, so
// players meet proper counter-play. It is never shown to the player.
//   node tools/counters.js [dist/duels.json]
const fs=require('fs'), path=require('path'), {execFileSync}=require('child_process');
const IN=process.argv[2]||path.resolve(__dirname,'..','dist','duels.json');
const D=JSON.parse(fs.readFileSync(IN,'utf8')); const cap=t=>Math.min(t,1500); const out={};
for(const id in D){ const a=D[id], C=a.cost; out[id]={};
  for(const A of a.att){ const s=a.solo[A]; if(!s) continue; const list=[];
    for(const B of a.def){ const r=a.pairs[A][B]; if(!r) continue; const v=(cap(s.tdmg)-cap(r.tdmg))/150+C[A]*(s.aRem-r.aRem)-C[B]*(1-r.bRem);
      if(v>=0&&r.tdmg<=Math.max(200,cap(s.tdmg)*0.35)) list.push([B,Math.round(v*10)/10]); }
    list.sort((x,y)=>y[1]-x[1]); out[id][A]=list.slice(0,8).map(x=>x[0]); } }
fs.writeFileSync(path.resolve(__dirname,'..','src','data_counters.js'),
`// GENERATED by tools/counters.js from duel results. Which cards answer which, per arena (AI use only).\nconst COUNTERS=${JSON.stringify(out)};\n`);
console.log('counters for',Object.keys(out).length,'arenas');
